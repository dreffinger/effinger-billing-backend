// Bundles the browser side (src/client.ts, which uses Neon's @neon/auth client) into one minified script and writes it into
// src/generated/client-bundle.ts as a string, so the Function can serve it at /app.js with no CDN and no second deployment.
import { build } from "esbuild";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const result = await build({
  entryPoints: [resolve(root, "src/client.ts")],
  bundle: true,
  minify: true,
  format: "iife",
  platform: "browser",
  target: ["es2022"],
  write: false,
  legalComments: "none",
  define: { "process.env.NODE_ENV": '"production"' },
});
const js = result.outputFiles[0].text;
const out = resolve(root, "src/generated/client-bundle.ts");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, "// generated by scripts/bundle-client.mjs - do not edit\nexport const CLIENT_JS = " + JSON.stringify(js) + ";\n");
console.log("client bundle: %d KB -> %s", Math.round(js.length / 1024), out);
